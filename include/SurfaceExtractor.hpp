// Custom hash for std::pair<int, int> to enable edge welding
struct PairHash {
    size_t operator()(const std::pair<int, int>& p) const {
        return std::hash<int>()(p.first) ^ (std::hash<int>()(p.second) << 1);
    }
};

class MarchingCubesExtractor {
private:
    double min_bound_;
    double max_bound_;
    int resolution_;

    // Standard Marching Cubes edge and triangle lookup tables
    static const int edgeTable[256];
    static const int triTable[256][18];
    static const int cornerPairs[12][2];

    int getGlobalCornerIndex(int i, int j, int k) const {
        int res_p1 = resolution_ + 1;
        return i + j * res_p1 + k * res_p1 * res_p1;
    }

public:
    MarchingCubesExtractor(double min_b = -2.0, double max_b = 2.0, int res = 32)
        : min_bound_(min_b), max_bound_(max_b), resolution_(res) {}

    pmp::SurfaceMesh extractMesh(const ImplicitSurface& surface) const {
        pmp::SurfaceMesh mesh;
        double step = (max_bound_ - min_bound_) / resolution_;
        int res_p1 = resolution_ + 1;

        // 1. Evaluate scalar field values and positions at grid corners
        std::vector<double> grid_values(res_p1 * res_p1 * res_p1);
        std::vector<pmp::Point> grid_points(res_p1 * res_p1 * res_p1);

        for (int i = 0; i <= resolution_; ++i) {
            double x = min_bound_ + i * step;
            for (int j = 0; j <= resolution_; ++j) {
                double y = min_bound_ + j * step;
                for (int k = 0; k <= resolution_; ++k) {
                    double z = min_bound_ + k * step;
                    int idx = getGlobalCornerIndex(i, j, k);
                    grid_points[idx] = pmp::Point(static_cast<float>(x), static_cast<float>(y), static_cast<float>(z));
                    grid_values[idx] = surface.eval(x, y, z);
                }
            }
        }

        // 2. Map global edge corner pairs to created pmp::Vertex handles for topological continuity
        std::unordered_map<std::pair<int, int>, pmp::Vertex, PairHash> edge_vertex_map;

        auto get_or_create_vertex = [&](int c1, int c2) -> pmp::Vertex {
            int u = std::min(c1, c2);
            int v = std::max(c1, c2);
            std::pair<int, int> key = {u, v};

            auto it = edge_vertex_map.find(key);
            if (it != edge_vertex_map.end()) {
                return it->second;
            }

            // Linear interpolation to find precise isosurface intersection
            double val1 = grid_values[c1];
            double val2 = grid_values[c2];
            double t = std::abs(val1 - val2) > 1e-12 ? (-val1) / (val2 - val1) : 0.5;
            t = std::clamp(t, 0.0, 1.0);

            pmp::Point p1 = grid_points[c1];
            pmp::Point p2 = grid_points[c2];
            pmp::Point p_interp = p1 + static_cast<float>(t) * (p2 - p1);

            pmp::Vertex new_v = mesh.add_vertex(p_interp);
            edge_vertex_map[key] = new_v;
            return new_v;
        };

        // 3. Process every voxel in the 3D grid
        for (int i = 0; i < resolution_; ++i) {
            for (int j = 0; j < resolution_; ++j) {
                for (int k = 0; k < resolution_; ++k) {
                    int corner_indices[8] = {
                        getGlobalCornerIndex(i,     j,     k),
                        getGlobalCornerIndex(i + 1, j,     k),
                        getGlobalCornerIndex(i + 1, j + 1, k),
                        getGlobalCornerIndex(i,     j + 1, k),
                        getGlobalCornerIndex(i,     j,     k + 1),
                        getGlobalCornerIndex(i + 1, j,     k + 1),
                        getGlobalCornerIndex(i + 1, j + 1, k + 1),
                        getGlobalCornerIndex(i,     j + 1, k + 1)
                    };

                    int cubeindex = 0;
                    for (int c = 0; c < 8; ++c) {
                        if (grid_values[corner_indices[c]] < 0.0) cubeindex |= (1 << c);
                    }

                    if (edgeTable[cubeindex] == 0) continue;

                    pmp::Vertex edge_verts[12];
                    for (int e = 0; e < 12; ++e) {
                        if (edgeTable[cubeindex] & (1 << e)) {
                            int c1 = corner_indices[cornerPairs[e][0]];
                            int c2 = corner_indices[cornerPairs[e][1]];
                            edge_verts[e] = get_or_create_vertex(c1, c2);
                        }
                    }

                    for (int t = 0; triTable[cubeindex][t] != -1; t += 3) {
                        pmp::Vertex v1 = edge_verts[triTable[cubeindex][t]];
                        pmp::Vertex v2 = edge_verts[triTable[cubeindex][t + 1]];
                        pmp::Vertex v3 = edge_verts[triTable[cubeindex][t + 2]];
                        if (v1 != v2 && v2 != v3 && v1 != v3) {
                            mesh.add_triangle(v1, v2, v3);
                        }
                    }
                }
            }
        }
        return mesh;
    }
};

